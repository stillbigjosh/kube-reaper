pub fn find_matching_permissions(
    resource: &str,
    verb: &str,
    api_group: &str,
) -> Vec<&'static DangerousPermission> {
    // Leak the vec to get 'static lifetime for pattern matching
    let patterns: &'static Vec<DangerousPermission> = Box::leak(Box::new(all_dangerous_permissions()));

    patterns
        .iter()
        .filter(|p| {
            let resource_match = p.resource == "*" || p.resource == resource;
            let verb_match = p.verbs.contains(&"*") || p.verbs.contains(&verb);
            let group_match = p.api_group == "*" || p.api_group == api_group;
            resource_match && verb_match && group_match
        })
        .collect()
}
