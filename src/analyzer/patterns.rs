use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
pub enum Severity {
    Critical,
    High,
    Medium,
    Low,
    Info,
}

impl Severity {
    pub fn label(&self) -> &'static str {
        match self {
            Severity::Critical => "CRITICAL",
            Severity::High => "HIGH",
            Severity::Medium => "MEDIUM",
            Severity::Low => "LOW",
            Severity::Info => "INFO",
        }
    }
}

impl std::fmt::Display for Severity {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.label())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum AttackCapability {
    NodeBreakout,
    ClusterAdmin,
    CredentialHarvest,
    CodeExecution,
    PersistentBackdoor,
    LateralMovement,
    PrivilegeEscalation,
    TrafficInterception,
    AdmissionBypass,
    InformationDisclosure,
    DenialOfService,
    LogInjection,
    NetworkBypass,
    IdentityForge,
}

impl std::fmt::Display for AttackCapability {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let s = match self {
            AttackCapability::NodeBreakout => "Node Breakout",
            AttackCapability::ClusterAdmin => "Cluster Admin Takeover",
            AttackCapability::CredentialHarvest => "Credential Harvest",
            AttackCapability::CodeExecution => "Code Execution",
            AttackCapability::PersistentBackdoor => "Persistent Backdoor",
            AttackCapability::LateralMovement => "Lateral Movement",
            AttackCapability::PrivilegeEscalation => "Privilege Escalation",
            AttackCapability::TrafficInterception => "Traffic Interception",
            AttackCapability::AdmissionBypass => "Admission Bypass",
            AttackCapability::InformationDisclosure => "Information Disclosure",
            AttackCapability::DenialOfService => "Denial of Service",
            AttackCapability::LogInjection => "Log Injection",
            AttackCapability::NetworkBypass => "Network Bypass",
            AttackCapability::IdentityForge => "Identity Forge",
        };
        write!(f, "{}", s)
    }
}

